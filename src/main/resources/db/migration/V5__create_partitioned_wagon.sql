--разбивка таблицы вагонов по месяцам
CREATE TABLE t_wagon (
id BIGINT GENERATED BY DEFAULT AS IDENTITY,
f_number BIGINT NOT NULL CHECK (f_number BETWEEN 20000000 AND 99999999),
f_category VARCHAR(255) NOT NULL
     CHECK (f_category IN ('TRANSIT_WITHOUT_PROCESSING', 'TRANSIT_WITH_PROCESSING', 'LOCAL')),
f_last_operation VARCHAR(255) NOT NULL
     CHECK (f_last_operation IN ('ARRIVAL', 'DEPARTURE', 'LOADING', 'UNLOADING', 'REPAIR',
                                 'PROCESSING', 'SPOTTING', 'REMOVAL', 'WAITING_SPOTTING',
                                 'WAITING_REMOVAL', 'WAITING_REPAIR', 'WAITING_OPER', 'DISBANDMENT')),
f_last_operation_at TIMESTAMP NOT NULL,
f_arrival_at TIMESTAMP NOT NULL CHECK (f_arrival_at >= TIMESTAMP '2024-01-01 00:00:00'),
f_departure_at TIMESTAMP,
f_loading VARCHAR(255) NOT NULL CHECK (f_loading IN ('NONE', 'LOADING', 'UNLOADING', 'BOTH')), PRIMARY KEY (id, f_departure_at)
) PARTITION BY RANGE (f_departure_at);

