CREATE TABLE t_wagon (
id BIGINT GENERATED BY DEFAULT AS IDENTITY,
PRIMARY KEY (id),
f_number BIGINT NOT NULL UNIQUE CHECK (f_number BETWEEN 20000000 AND 99999999),
f_category VARCHAR(255) NOT NULL CHECK (f_category IN ('TRANSIT_WITHOUT_PROCESSING',
                                                   'TRANSIT_WITH_PROCESSING',
                                                   'LOCAL')),
f_last_operation VARCHAR(255) NOT NULL CHECK (f_last_operation IN ('ARRIVAL', 'DEPARTURE', 'LOADING', 'UNLOADING',
                                             'REPAIR', 'PROCESSING', 'SPOTTING', 'REMOVAL',
                                             'WAITING_SPOTTING', 'WAITING_REMOVAL',
                                             'WAITING_REPAIR', 'WAITING_OPER', 'DISBANDMENT')),
f_last_operation_at TIMESTAMP NOT NULL,
f_arrival_at TIMESTAMP NOT NULL CHECK (f_arrival_at >= TIMESTAMP '2024-01-01 00:00:00'),
f_departure_at TIMESTAMP,
f_loading VARCHAR(255) NOT NULL CHECK (f_loading IN ('NONE', 'LOADING', 'UNLOADING', 'BOTH')),
-- дата отправления позже даты прибытия (если отправление задано)
CHECK (f_departure_at IS NULL OR f_arrival_at < f_departure_at),
-- время последней операции не раньше прибытия
CHECK (f_last_operation_at >= f_arrival_at),
-- если последняя операция — отправление, дата отправления обязана быть
CHECK (f_last_operation <> 'DEPARTURE' OR f_departure_at IS NOT NULL),
-- если последняя операция — отправление, время операции равно времени отправления
CHECK (f_last_operation <> 'DEPARTURE' OR f_last_operation_at = f_departure_at),
-- если операция не отправление, даты отправления ещё нет
CHECK (f_last_operation = 'DEPARTURE' OR f_departure_at IS NULL),
-- грузовые операции (погрузка/выгрузка) допустимы только для местных вагонов
CHECK (f_category = 'LOCAL' OR f_loading = 'NONE')
);