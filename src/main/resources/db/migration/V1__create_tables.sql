CREATE TABLE t_block (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    PRIMARY KEY (id),
    f_title VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE t_metric (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    PRIMARY KEY (id),
    f_metric_name VARCHAR(255) NOT NULL UNIQUE,
    f_block_id BIGINT NOT NULL,
    f_type VARCHAR(255) NOT NULL CHECK (f_type IN ('MANUAL', 'CALCULATED')),
    f_unit VARCHAR(255) NOT NULL
);

CREATE TABLE t_metric_value (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    PRIMARY KEY (id),
    f_metric_id BIGINT NOT NULL,
    f_month INTEGER NOT NULL CHECK (f_month BETWEEN 1 AND 12),
    f_year INTEGER NOT NULL CHECK (f_year >= 2024),
    f_plan NUMERIC(10,1),
    f_fact NUMERIC(10,1),
    f_updated_at TIMESTAMP(6),
    f_updated_by VARCHAR(255),
    CONSTRAINT uk_metric_value_metric_month_year UNIQUE (f_metric_id, f_month, f_year)
);

ALTER TABLE t_metric
    ADD CONSTRAINT fk_metric_block
        FOREIGN KEY (f_block_id) REFERENCES t_block (id);

ALTER TABLE t_metric_value
    ADD CONSTRAINT fk_metric_value_metric
        FOREIGN KEY (f_metric_id) REFERENCES t_metric (id);